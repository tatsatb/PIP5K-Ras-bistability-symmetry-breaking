function param = param_list
% list of parameters

%% Spatial domain parameters
    Rc   = 5;   % radius of cell (um)
    param.Np = 314; % number of spatial point along the perimeter
    param.x = linspace(0,2*pi*Rc,param.Np); 
    param.dx = mean(diff(param.x));   % spatial steps (um)

%% Time parameters
    param.t0 = 0;   % Length of simulation (s)
    param.tf = 900;   % Length of simulation (s)
    param.dt = 0.001; % s

%% Reaction parameters
    %--------------------------------------------------------------------------
    % dRas_dt
    %--------------------------------------------------------------------------
    param.a1 = 0.1263;
    param.a2 = 2.7075;
    param.a3 = 1.0830;
    param.a4 = 462; 
    param.a5 = 9.5000e-04;
    %--------------------------------------------------------------------------
    % dPIP2_dt
    %--------------------------------------------------------------------------  
    param.b1 = 0.0137;
    param.b2 = 2.0273e+03;
    param.b3 = 1.6618; 
    param.b4  = 5.1870; % activation of PIP2 by PIP5K (membrane)
    %--------------------------------------------------------------------------
    % dPKB_dt 
    %--------------------------------------------------------------------------
    param.c1 = 0.0707;
    param.c2 = 0.8208;
    %--------------------------------------------------------------------------
    % dPIP5K_dt 
    %--------------------------------------------------------------------------
    param.d1 = 0.95;
    param.d2 = 0.02;
    param.d3 = 0.3562;
    %--------------------------------------------------------------------------
    % dActin_dt 
    %--------------------------------------------------------------------------
    param.ac1 = 0.0475; % referred as p1 in Y. Deng et al
    param.ac2 = 0.0475; % referred as p2 in Y. Deng et al
    %--------------------------------------------------------------------------
    % dMyosin_dt 
    %--------------------------------------------------------------------------

    param.m1  = 0.0380; 
    param.m2  =  0.0380;
    %--------------------------------------------------------------------------
    % Diffusion coefficients
    %--------------------------------------------------------------------------
    param.DRas  = 0.0091;
    param.DPIP2 = 0.0069;
    param.DPKB  = 0.0207;

    param.DActin  = 0.0012;
    param.DMyosin = 0.0023;

    param.DPIP5K_cyto = 4.6056;
    param.DPIP5K_mem  = 0.0576;
    %--------------------------------------------------------------------------
    % Noise 
    %--------------------------------------------------------------------------
    param.alpha = 0.0924;
    %--------------------------------------------------------------------------
    % Membrane tension parameters
    %--------------------------------------------------------------------------
    param.e1 = 0.1250;
    param.e2 = 0.1250;
    %--------------------------------------------------------------------------
    param.Tmem = 0.1375; % membrane tension-mediated global negative feedback strength on Ras
    %--------------------------------------------------------------------------